import type { HttpResult, JournalEntry, UndoableClient } from './runtime.js';
import { refNames } from './spec.js';
import type { ApiSpec, Schema } from './types.js';

/** The shape `undogen types` generates for each operation. */
export interface OperationTypes {
  params: Record<string, string | number>;
  query?: Record<string, unknown>;
  body?: unknown;
  response: unknown;
}

/** Input of a typed call: path params, query and body as the operation declares them. */
export type TypedInput<O extends OperationTypes> = (keyof O['params'] extends never ? { params?: O['params'] } : { params: O['params'] }) &
  (undefined extends O['query'] ? { query?: O['query'] } : { query: O['query'] }) &
  (undefined extends O['body'] ? { body?: O['body'] } : { body: O['body'] }) & { headers?: Record<string, string> };

/**
 * A type-checked view of an UndoableClient, using interfaces generated by `undogen types`:
 *
 *   import type { Operations } from './api-types.js';
 *   const api = typed<Operations>(client);
 *   const todo = await api.call('createTodo', { body: { title: 'x' } }); // todo.data is a Todo
 */
export function typed<Ops extends { [K in keyof Ops]: OperationTypes }>(client: UndoableClient) {
  return {
    client,
    call<K extends keyof Ops & string>(operationId: K, input: TypedInput<Ops[K]>): Promise<Omit<HttpResult, 'data'> & { data: Ops[K]['response']; entry?: JournalEntry }> {
      return client.call(operationId, input as Parameters<UndoableClient['call']>[1]) as never;
    },
  };
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k));

/** Shared schemas emitted once as named aliases (resolved $refs are shared objects). */
type Names = Map<object, string>;

/** A TypeScript type for a JSON Schema (the subset OpenAPI uses). */
export function schemaToTs(s: Schema | undefined, depth = 0, names?: Names, defining?: object): string {
  if (!s || typeof s !== 'object' || depth > 8) return 'unknown';
  const alias = names?.get(s);
  if (alias && s !== defining) return alias;
  const variants = (s['x-undogen-variants'] ?? s.oneOf ?? s.anyOf) as Schema[] | undefined;
  if (Array.isArray(variants) && variants.length) return variants.map((v) => schemaToTs(v, depth + 1, names)).join(' | ');
  if (Array.isArray(s.enum) && s.enum.length) return s.enum.map((e) => JSON.stringify(e)).join(' | ');
  if (s.const !== undefined) return JSON.stringify(s.const);
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : s.properties ? ['object'] : s.items ? ['array'] : [];
  const nullable = s.nullable === true || types.includes('null');
  const parts = types
    .filter((t) => t !== 'null')
    .map((t) => {
      switch (t) {
        case 'string':
          return 'string';
        case 'integer':
        case 'number':
          return 'number';
        case 'boolean':
          return 'boolean';
        case 'array':
          return `Array<${Array.isArray(s.items) ? 'unknown' : schemaToTs(s.items as Schema, depth + 1, names)}>`;
        case 'object': {
          const required = new Set(s.required ?? []);
          const props = Object.entries(s.properties ?? {}).map(
            ([k, v]) => `${key(k)}${required.has(k) ? '' : '?'}: ${schemaToTs(v, depth + 1, names)}`,
          );
          const extra = s.additionalProperties;
          // With named (possibly optional) properties, a typed index signature would conflict with them: use unknown.
          if (extra && typeof extra === 'object' && !props.length) props.push(`[key: string]: ${schemaToTs(extra as Schema, depth + 1, names)}`);
          else if (!s.properties || extra === true || (extra && typeof extra === 'object')) props.push('[key: string]: unknown');
          return `{ ${props.join('; ')} }`;
        }
        default:
          return 'unknown';
      }
    });
  const out = parts.length ? parts.join(' | ') : 'unknown';
  return nullable ? `${out} | null` : out;
}

/**
 * TypeScript declarations for every operation of a spec, for `typed<Operations>(client)`.
 */
export function generateTypes(spec: ApiSpec): string {
  // Object schemas reached more than once are shared $refs: name them and emit each once.
  const uses = new Map<object, number>();
  const walk = (s: unknown, depth: number) => {
    if (!s || typeof s !== 'object' || depth > 8) return;
    const sch = s as Schema;
    if (sch.properties) {
      const n = (uses.get(sch) ?? 0) + 1;
      uses.set(sch, n);
      if (n > 1) return; // already walked
    }
    for (const v of Object.values(sch.properties ?? {})) walk(v, depth + 1);
    if (sch.items && !Array.isArray(sch.items)) walk(sch.items, depth + 1);
    for (const v of ((sch['x-undogen-variants'] ?? sch.oneOf ?? sch.anyOf) as Schema[] | undefined) ?? []) walk(v, depth + 1);
    if (sch.additionalProperties && typeof sch.additionalProperties === 'object') walk(sch.additionalProperties, depth + 1);
  };
  for (const op of spec.operations) {
    walk(op.requestSchema, 0);
    walk(op.responseSchema, 0);
  }
  const names: Names = new Map();
  const taken = new Set<string>(['Operations']);
  const byRef = new Map<string, string>(); // one alias per $ref, even if it was normalized at several depths
  const emit: Array<[object, string]> = [];
  for (const [sch, n] of uses) {
    const ref = refNames.get(sch);
    if (ref && byRef.has(ref)) {
      names.set(sch, byRef.get(ref)!);
      continue;
    }
    if (n < 2 && !(ref && [...uses.keys()].some((o) => o !== sch && refNames.get(o) === ref))) continue;
    const title = ref ?? (typeof (sch as Schema).title === 'string' ? ((sch as Schema).title as string) : '');
    let base = title.replace(/[^A-Za-z0-9]+(.)?/g, (_, c: string | undefined) => (c ? c.toUpperCase() : '')).replace(/^[^A-Za-z]+/, '');
    base = base ? base[0]!.toUpperCase() + base.slice(1) : 'Schema';
    let name = base;
    for (let i = 2; taken.has(name); i++) name = `${base}${i}`;
    taken.add(name);
    names.set(sch, name);
    emit.push([sch, name]);
    if (ref) byRef.set(ref, name);
  }
  const lines = [
    `// Generated by undogen from ${spec.title} ${spec.version}. Do not edit: run \`undogen types\` again.`,
    '',
  ];
  for (const [sch, name] of emit) lines.push(`export type ${name} = ${schemaToTs(sch as Schema, 0, names, sch)};`);
  if (emit.length) lines.push('');
  lines.push('export interface Operations {');
  for (const op of spec.operations) {
    const params = op.pathParams.map((p) => `${key(p)}: string | number`).join('; ');
    const query = op.queryParams.length
      ? `{ ${op.queryParams.map((q) => `${key(q.name)}${q.required ? '' : '?'}: ${schemaToTs(q.schema, 0, names)}`).join('; ')} }`
      : undefined;
    const queryRequired = op.queryParams.some((q) => q.required);
    const hasBody = op.method !== 'get' && (op.requestSchema || op.requestExample !== undefined);
    const doc = (op.summary ?? '').replace(/\*\//g, '*\\/');
    if (doc) lines.push(`  /** ${doc} (${op.method.toUpperCase()} ${op.path}) */`);
    lines.push(`  ${key(op.id)}: {`);
    lines.push(`    params: { ${params} };`);
    if (query) lines.push(`    query${queryRequired ? '' : '?'}: ${query};`);
    if (hasBody) lines.push(`    body: ${schemaToTs(op.requestSchema, 0, names)};`);
    lines.push(`    response: ${schemaToTs(op.responseSchema, 0, names)};`);
    lines.push('  };');
  }
  lines.push('}', '');
  return lines.join('\n');
}
